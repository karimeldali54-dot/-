def emit(rows, culture):
    lines = []
    for rec in rows:
        i, name, kind, value, period, material, place, museum, clue, *img = rec
        image = img[0] if img else ""
        # auto clue already hand-written and must not include the name
        assert name not in clue, name
        fields = [i, name, culture, kind, str(value), period, material, place, museum, clue, image]
        assert all("|" not in f for f in fields)
        lines.append("|".join(fields))
    return lines

